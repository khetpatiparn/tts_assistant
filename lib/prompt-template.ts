export type PromptFormData = {
  productName: string;
  productInfo: string;
  riskModule: string;
  extraNotes: string;
  imageCaptions: string[];
  angle: string;
  productSpec: string;
  safeMode: boolean;
};

export function buildPromptText({
  productName,
  productInfo,
  riskModule,
  extraNotes,
  imageCaptions,
  angle,
  productSpec,
  safeMode,
}: PromptFormData): string {
  const imageLines = imageCaptions
    .map((caption, index) => `รูปที่ ${index + 1}: ${caption || "[ไม่มีคำอธิบาย]"}`)
    .join("\n");

  // angle ว่าง = พฤติกรรมเดิมทุกตัวอักษร (entry เดิมทั้งหมดยังไม่มี angle)
  // angle ไม่ว่าง = ล็อกแกนคลิปไว้ และต้องถอนคำสั่ง "เลือก use case เอง" ออก
  // ไม่งั้นโจทย์จะมีสองประโยคที่ขัดกันเอง
  const trimmedAngle = angle.trim();
  const angleBlock =
    trimmedAngle === ""
      ? "\n"
      : `
Angle ที่ต้องใช้สำหรับคลิปนี้ (บังคับ ห้ามเปลี่ยนเอง):
"""
${trimmedAngle}
"""
`;
  // โหมดปลอดภัยชนะ angle เพราะมันตัดการสาธิตทั้งหมดทิ้ง — ถ้าปล่อยให้ angle สั่งต่อ
  // จะได้โจทย์ที่ขัดกันเอง (angle บอกให้โชว์ตอนใช้งาน แต่โหมดบอกว่าห้ามใช้งาน)
  const useCaseRule = safeMode
    ? "- ไม่ต้องเลือก use case และไม่ต้องสาธิตการใช้งาน คลิปนี้ทำหน้าที่โชว์ตัวสินค้าให้ชัดที่สุดเท่านั้น"
    : trimmedAngle === ""
      ? "- เลือก use case เดียวที่เหมาะที่สุด เสี่ยงเพี้ยนน้อย และขายของได้ใน 10 วินาที"
      : "- ใช้ Angle ที่กำหนดไว้ด้านบนเป็นแกนของคลิป ห้ามเลือก use case อื่นเอง แต่ยังต้องเลือกวิธีนำเสนอที่เสี่ยงเพี้ยนน้อยและขายของได้ใน 10 วินาที";

  // กฎ 3 ชุดด้านล่างคือทุกจุดในเทมเพลตที่สั่งให้ "สินค้าขยับ" — โหมดปลอดภัยต้องสลับให้ครบทั้งสามจุด
  // ไม่งั้นโมเดลจะได้คำสั่งขัดกันเอง (เคยเป็นเหตุให้ output เพี้ยนมาแล้วตอนใส่ angle อย่างเดียว)
  const actionRule = safeMode
    ? "- ห้ามให้ตัวสินค้าเคลื่อนไหว เปลี่ยนรูป กาง พับ เปิด ปิด หมุนเอง หรือถูกใช้งานโดยเด็ดขาด"
    : "- เลือก action ที่ง่ายที่สุดแต่เห็นประโยชน์สินค้าเร็ว";

  const beatsRules = safeMode
    ? `- ใช้ 3–4 camera beats แทน action beats โดยแต่ละ beat คือมุมกล้อง/ระยะที่ต่างกันของสินค้าตัวเดิมในตำแหน่งเดิม
- Action Timeline ให้เขียนเป็นลำดับการเคลื่อนกล้อง (orbit ช้า / dolly เข้า / tilt / rack focus) ไม่ใช่ลำดับการกระทำ
- ห้ามมีคน มือ นิ้ว หรือส่วนใดของร่างกายปรากฏในเฟรมเด็ดขาด`
    : `- เลือกจำนวน visual beats ให้เหมาะกับความเสี่ยงของสินค้า
- ถ้าสินค้าเสี่ยงเพี้ยนสูง เช่น พับได้ กางได้ ยืดได้ หมุนได้ มีโครงขา หรือมีกลไก ให้ใช้ 3–4 visual beats ที่ปลอดภัยกว่า
- ถ้าสินค้าเสี่ยงต่ำ ให้ใช้ 4–5 visual beats เพื่อให้คลิปมีจังหวะ`;

  const movementRule = safeMode
    ? "- ภายใน 2 วินาทีแรกต้องมี movement ชัดเจน โดย movement นั้นต้องมาจากกล้องเท่านั้น ไม่ใช่จากตัวสินค้า"
    : "- ภายใน 2 วินาทีแรกต้องมี movement ชัดเจน";

  // สเปกที่ขั้นที่ 0 สกัดจากรูปมาให้ — ป้อนเป็นข้อความเพื่อให้ขั้นนี้ไม่ต้องดึงข้อเท็จจริง
  // จากรูปเองระหว่างที่ต้องแต่งฉาก/กล้อง/บทพูดไปด้วย ซึ่งเป็นจุดที่รายละเอียดเคยหาย
  const trimmedSpec = productSpec.trim();
  const specBlock =
    trimmedSpec === ""
      ? ""
      : `
สเปกสินค้าที่สกัดจากรูป (ความจริงหลักเรื่องข้อเท็จจริงของสินค้า ถ้าขัดกับข้อมูลร้านให้ยึดอันนี้):
"""
${trimmedSpec}
"""
`;

  return `ใช้ Core Prompt ด้านบนสร้าง prompt สำหรับ Gemini Flow

ให้วิเคราะห์ข้อมูลสินค้า รูปอ้างอิง, Product Accuracy, Product Risk, Category Module, Shot / Angle Template และ Performance Card ภายในก่อน
แต่ไม่ต้องแสดง Product Card หรือ Performance Card ออกมา

ให้ output เฉพาะ prompt สำหรับ Gemini Flow ตามโครงสร้าง 10 ส่วนของ Core Prompt
โดยเขียนให้กระชับ ไม่ซ้ำ ไม่มีคำสั่งที่ขัดกัน และเหมาะกับคลิป 10 วินาที

ชื่อสินค้า:
"""
${productName}
"""

รูปอ้างอิงที่แนบ (แต่ละใบมี caption กำกับ และจะถูกแนบให้ดูทีละใบพร้อม caption ด้านล่างของโจทย์นี้):
${imageLines}

ข้อมูลสินค้าจากเว็บ/ร้านค้า:
"""
${productInfo}
"""
${specBlock}
Product Risk Module ที่ต้องใช้:
"""
${riskModule}
"""

ข้อมูลเพิ่มเติมจากฉัน ถ้ามี:
"""
${extraNotes}
"""${angleBlock}
สิ่งที่ต้องทำ:
${useCaseRule}
${actionRule}
- อ่านรูปอ้างอิงแต่ละใบตาม caption ที่กำกับ แล้วถอดโครงสร้างที่เห็นจริง (รูปทรง สี ชิ้นส่วน สัดส่วน ตำแหน่ง logo ด้านหน้า/หลัง กลไก) ลง Product Accuracy และ Critical Product Structure — **ต้องบรรยายพื้นผิว/วัสดุ และกลไกการใช้งานของส่วนที่ถูกใช้ในคลิปเสมอ** ไม่ว่าจะประเมินว่าสินค้าเสี่ยงเพี้ยนสูงหรือต่ำก็ตาม
- ห้ามใช้คำที่กำกวมในการบรรยายสินค้า — ระบุทรงให้ชัด (กล่อง/โหล/ถัง ไม่ใช่คำรวมๆ) และระบุพื้นผิวให้ชัด (ทึบ หรือ มีรู/ตะแกรง ไม่ใช่คำว่า "โปร่ง") และใช้คำเรียกสินค้าแบบเดียวกันตลอดพรอมต์
- caption ของรูปคือความจริงเรื่องด้าน/ชิ้นส่วน ใช้เพื่อไม่ให้ output บรรยายผิดด้าน (เช่นถ้า caption บอก logo อยู่ด้านหน้าเท่านั้น ห้ามให้ output ใส่ logo ด้านหลัง)
- วิเคราะห์ Product Accuracy ที่ห้ามพลาดจากรูปและข้อมูลสินค้า
- วิเคราะห์ Critical Product Structure ที่ต้องคงไว้
- วิเคราะห์จุดที่ AI มีโอกาสทำเพี้ยน แล้วใส่กันไว้ใน Product Accuracy / Negative Prompt
${beatsRules}

กฎสำคัญ:
- ใช้รูปอ้างอิงเป็นหลักก่อนข้อมูลเว็บ
- ห้ามเดาคุณสมบัติที่ไม่มีในรูปหรือข้อมูลสินค้า
- ถ้าไม่แน่ใจ ให้เลือกทาง conservative และเสี่ยงเพี้ยนน้อยที่สุด
- ห้ามเคลมเกินจริง
- ต้องเห็นสินค้าใน 1–2 วินาทีแรก
${movementRule}
- คลิปต้องเร็ว แต่ห้ามทำให้สินค้า วิธีใช้ หรือโครงสร้างเพี้ยน
- ห้ามมีข้อความทุกชนิดในวิดีโอ
- ห้ามซับ ห้าม label ห้าม poster ห้าม UI overlay ห้าม callout ห้ามราคา ห้ามตัวหนังสือในฉากหลัง
- บทพากย์ไทยเท่านั้น 3–5 วลี/จังหวะพูดสั้น รวมประมาณ 30–35 คำเท่านั้นและห้ามเกิน 35 คำ มี hook ใน 1–2 วินาทีแรก และไม่มี dead air ยาว

**important**:
กรณีที่เป็นสินค้าแนวน้ำยาปรับผ้านุ่ม/ซักผ้า/ล้างจาน/ของเหลวต่างๆ
เนื่องจากสินค้าแนวของเหลวมักจะไม่มีรูปที่เป็นของเหลวต้นฉบับให้ จึงต้องไม่เน้นไปเรื่องการเทให้เห็นของเหลว
ไม่ควรให้คลิปพึ่งการเห็นตัวของเหลวเป็นหลัก
ให้ทำแนว Package-led UGC คือ "แพ็กเกจเป็นพระเอก + before /after ของการแก้ปัญหาที่ได้จากการใช้สินค้าแทน"

Output:
สร้าง prompt สำหรับ Gemini Flow ตาม 10 ส่วนนี้เท่านั้น:
1. Style
2. Scene
3. Subject
4. Product Accuracy
5. Action Timeline
6. Camera
7. Framing
8. Lighting / Color
9. Negative Prompt
10. Quick QA Checklist`;
}

